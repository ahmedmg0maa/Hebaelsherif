import { expect, test } from '@playwright/test'

test('homepage fits phone, tablet and desktop using the existing Arabic brand', async ({ page }, info) => {
  test.skip(info.project.name !== 'adaptive-chromium', 'Desktop Chromium runs the full width matrix')
  test.setTimeout(90_000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect((await page.goto('/'))?.status()).toBe(200)
    await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
    await expect(page.locator('h1')).toHaveCount(1)
    await expect(page.locator('h1')).toHaveCSS('font-family', /Amiri/)
    await expect(page.locator('body')).toHaveCSS('font-family', /IBM Plex Arabic/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await expect(page.locator('.home-hero a[href="/booking"]')).toBeInViewport()
    await expect(page.locator('video, audio, [autoplay]')).toHaveCount(0)
    await expect(page.locator('main picture')).toHaveCount(10)
    await expect(page.getByText('الصور في هذه الصفحة مولّدة بالذكاء الاصطناعي لأغراض التصميم.')).toBeVisible()
  }
})

test('scroll reveals the timeline and leaves the supplied images stationary', async ({ page }) => {
  await page.goto('/')
  const panel = page.locator('.home-track').first()
  const image = page.locator('.home-track-panels img')
  await panel.scrollIntoViewIfNeeded()
  const original = await image.boundingBox()
  const width = await panel.evaluate(node => node.getBoundingClientRect().width)
  await panel.getByRole('link').focus()
  await expect(panel.locator('.home-track-description')).toHaveCSS('opacity', '1')
  const desktopPointer = await page.evaluate(() => matchMedia('(min-width: 860px) and (hover: hover) and (pointer: fine)').matches)
  if (desktopPointer) await expect.poll(() => panel.evaluate(node => node.getBoundingClientRect().width)).toBeGreaterThan(width + 10)
  const after = await image.boundingBox()
  expect(after?.width).toBe(original?.width)
  expect(after?.height).toBe(original?.height)
  await expect(image).toHaveCSS('transform', 'none')

  const steps = page.locator('[data-home-step]')
  await steps.last().scrollIntoViewIfNeeded()
  await expect.poll(() => page.locator('[data-home-step][data-step-active]').count()).toBeGreaterThan(0)
  await expect(page.locator('.home-header')).toHaveAttribute('data-solid', '')
  await expect.poll(() => page.locator('.home-header').evaluate(node => Number((node as HTMLElement).style.getPropertyValue('--home-scroll')))).toBeGreaterThan(0)
  for (const photo of await page.locator('main picture img').all()) {
    await expect(photo).toHaveCSS('transform', 'none')
    await expect(photo).toHaveCSS('animation-name', 'none')
  }
})

test('mobile menu works with the keyboard and touch and reduced motion permits reading', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const menu = page.locator('.home-menu')
  const trigger = menu.locator('summary')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(menu).toHaveAttribute('open', '')
  await menu.getByRole('link', { name: 'المسارات', exact: true }).focus()
  await page.keyboard.press('Escape')
  await expect(menu).not.toHaveAttribute('open')
  await expect(trigger).toBeFocused()
  if (info.project.use.hasTouch) {
    await trigger.tap()
    await menu.getByRole('link', { name: 'المسارات', exact: true }).tap()
  } else {
    await page.keyboard.press('Enter')
    await menu.getByRole('link', { name: 'المسارات', exact: true }).focus()
    await page.keyboard.press('Enter')
  }
  await expect(page).toHaveURL(/#tracks$/)
  await expect(menu).not.toHaveAttribute('open')
  await expect(page.locator('.home-track-description').first()).toHaveCSS('opacity', '1')
  await expect(page.locator('.home-hero-line > span').first()).toHaveCSS('animation-name', 'none')
  await expect(page.locator('.home-scroll-cue span')).toHaveCSS('animation-name', 'none')
  await expect(page.locator('[data-tilting]')).toHaveCount(0)
})

test('homepage preserves the exercise and opens the existing booking flow', async ({ page }, info) => {
  test.setTimeout(60_000)
  await page.goto('/')
  const practice = page.locator('[data-learning-tour]')
  await practice.getByRole('tab', { name: 'جرّبي التطبيق' }).click()
  const fields = practice.getByRole('tabpanel').getByRole('textbox')
  await expect(fields).toHaveCount(2)
  await fields.nth(0).fill('ترتيب يومي')
  await fields.nth(1).fill('اختيار مهمة واحدة')
  await practice.getByRole('button', { name: /راجعي خطوتكِ/ }).click()
  await expect(practice.getByRole('tabpanel')).toContainText('اختيار مهمة واحدة')
  const booking = page.locator('.home-final a[href="/booking"]')
  // Use a settled position. A touch during the smooth scroll cancels the scroll.
  await booking.evaluate(link => link.scrollIntoView({ behavior: 'instant', block: 'center' }))
  await expect(page.locator('.home-final [data-home-reveal]')).not.toHaveAttribute('data-reveal-pending')
  if (info.project.use.hasTouch) await booking.tap()
  else await booking.click()
  await expect(page).toHaveURL(/\/booking$/, { timeout: 15_000 })
  await expect(page.getByRole('heading', { level: 1 })).toHaveCount(1)
})

test('a course card tilts on a fine pointer while its backdrop stays still', async ({ page }, info) => {
  test.skip(info.project.name !== 'adaptive-chromium', 'This interaction requires a fine mouse pointer')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const card = page.locator('[data-home-tilt]').first()
  const backdrop = page.locator('.home-courses picture img')
  const imageGeometry = () => backdrop.evaluate(image => {
    const box = image.getBoundingClientRect()
    return [box.x + scrollX, box.y + scrollY, box.width, box.height]
  })
  await card.scrollIntoViewIfNeeded()
  const originalImage = await imageGeometry()
  await card.hover({ position: { x: 34, y: 36 } })
  await expect(card).not.toHaveCSS('transform', 'none')
  await expect(backdrop).toHaveCSS('transform', 'none')
  expect(await imageGeometry()).toEqual(originalImage)
  await page.mouse.move(4, 4)
  await expect(card).toHaveCSS('transform', 'none')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await card.hover({ position: { x: 34, y: 36 } })
  await expect(card).toHaveCSS('transform', 'none')
})
